#!/usr/bin/env python3
"""Score labeling-design + estimator procedures against the benchmark objective.

Objective: estimate the population mean count as efficiently as possible while keeping
nominal 90% coverage.

  * A procedure is a (design, method) pair, compared at the same number of labeling
    draws n. (Under PPS a few draws repeat an image, so PPS uses slightly fewer distinct
    labels; this disadvantages PPS a little.)
  * Cells are (dataset, n) with n >= 25; n = 10 is reported separately because almost no
    procedure is calibrated there.
  * "Keeps coverage": mean coverage over cells >= 0.88 and every cell >= 0.80. With 100
    repeats per cell a coverage estimate has standard error ~0.03, so these thresholds
    tolerate Monte Carlo noise around 0.90 but not systematic undercoverage.
  * Efficiency: geometric mean over cells of interval width relative to the reference
    procedure (SRS + PPI difference estimator) on the same dataset and n. Relative RMSE is
    reported alongside.

  python scripts/leaderboard.py [--results results/benchmark.csv ...] [--datasets ...]
"""

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from countcal.methods import all_methods  # noqa: E402

REFERENCE = ("srs", "ppi")
MIN_N = 25
MEAN_COV, MIN_COV = 0.88, 0.80


def cell_metrics(df: pd.DataFrame) -> pd.DataFrame:
    df = df[df.estimand == "mean"]
    df = df.assign(covered=(df.lo <= df.truth) & (df.truth <= df.hi), width=df.hi - df.lo,
                   sq_err=(df.point - df.truth) ** 2)
    return df.groupby(["dataset", "design", "method", "n"]).agg(
        coverage=("covered", "mean"), width=("width", "mean"), rmse=("sq_err", lambda x: np.sqrt(x.mean())),
        reps=("rep", "size")).reset_index()


def score(cells: pd.DataFrame) -> pd.DataFrame:
    ref = cells[(cells.design == REFERENCE[0]) & (cells.method == REFERENCE[1])][["dataset", "n", "width", "rmse"]]
    c = cells.merge(ref, on=["dataset", "n"], suffixes=("", "_ref"))
    c["rel_width"] = c.width / c.width_ref
    c["rel_rmse"] = c.rmse / c.rmse_ref
    main = c[c.n >= MIN_N]
    g = main.groupby(["design", "method"])
    out = g.agg(cells=("coverage", "size"), mean_cov=("coverage", "mean"), min_cov=("coverage", "min"),
                width_vs_ppi=("rel_width", lambda x: float(np.exp(np.log(x).mean()))),
                rmse_vs_ppi=("rel_rmse", lambda x: float(np.exp(np.log(x).mean()))))
    worst = main.loc[main.groupby(["design", "method"]).coverage.idxmin(), ["design", "method", "dataset", "n"]]
    out = out.join(worst.set_index(["design", "method"]).rename(columns={"dataset": "worst_dataset", "n": "worst_n"}))
    small = c[c.n < MIN_N].groupby(["design", "method"]).coverage.mean().rename("cov_n10")
    out = out.join(small)
    out["keeps_coverage"] = (out.mean_cov >= MEAN_COV) & (out.min_cov >= MIN_COV)
    labels = {k: m.label for k, m in all_methods().items()}
    out = out.reset_index()
    out.insert(2, "label", out.method.map(labels).fillna(out.method))
    return out.sort_values(["keeps_coverage", "width_vs_ppi"], ascending=[False, True])


def to_md(t: pd.DataFrame) -> str:
    cols = ["design", "method", "label", "keeps_coverage", "width_vs_ppi", "rmse_vs_ppi", "mean_cov", "min_cov",
            "worst_dataset", "worst_n", "cov_n10", "cells"]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in t[cols].iterrows():
        vals = []
        for c in cols:
            v = r[c]
            vals.append("yes" if v is True else "no" if v is False else f"{v:.3f}" if isinstance(v, float) else str(v))
        lines.append("| " + " | ".join(vals) + " |")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", nargs="+", default=["results/benchmark.csv"])
    ap.add_argument("--datasets", nargs="+", default=None)
    ap.add_argument("--out", default="results/leaderboard.md")
    args = ap.parse_args()

    df = pd.concat([pd.read_csv(p) for p in args.results], ignore_index=True)
    df = df.drop_duplicates(["dataset", "design", "n", "rep", "method", "estimand"], keep="last")
    if args.datasets:
        df = df[df.dataset.isin(args.datasets)]
    cells = cell_metrics(df)
    real = [d for d in cells.dataset.unique() if not d.startswith("synth")]
    sections = [("All datasets", score(cells)), ("Real datasets only", score(cells[cells.dataset.isin(real)]))]
    md = ["# Leaderboard\n", __doc__.split("\n\n")[1].strip() + "\n",
          f"Generated by `scripts/leaderboard.py` from {', '.join(args.results)}.\n"]
    for title, t in sections:
        md += [f"## {title}\n", to_md(t), ""]
    Path(args.out).write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
